#!/usr/bin/env node
// Sync shared AI rules, skills, agents, hooks and workflows from AI-Master-Instructions
// into this project, as pinned by .ai-master.json. No dependencies; Node 18 or newer.
//
//   node .claude/master/sync.mjs              sync to the version in .ai-master.json
//   node .claude/master/sync.mjs --check      verify synced files against .ai-master.lock (CI)
//   node .claude/master/sync.mjs --dry-run    show what a sync would change
//   --source DIR (or AI_MASTER_DIR)           use a local master checkout instead of cloning
//   --target DIR                              project root (default: current directory)
//
// Synced files are owned by the master: change them there, never here (rule SRC-06).

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MASTER_REPO = 'https://github.com/DdraigFawr13/AI-Master-Instructions';
export const MANIFEST = '.ai-master.json';
export const LOCK = '.ai-master.lock';
export const RULES_OUT = '.claude/master/RULES.md';
export const SCRIPT_OUT = '.claude/master/sync.mjs';
export const BUDGET_FILES = [RULES_OUT, 'AGENTS.md', 'CLAUDE.md'];
const SYNCED_KINDS = new Set(['skill', 'agent', 'hook', 'workflow']);
const RULE_LINE = /^- \*\*([A-Z]+-\d+)\*\* (.*)$/;
const WHY_LINE = /^\s+<!-- why: (.+?) \| source: (.+?) -->$/;
const PRETTIER_START = '# ai-master:start (managed by .claude/master/sync.mjs)';
const PRETTIER_END = '# ai-master:end';

export class SyncError extends Error {}

// ---------- rules ----------

/** Parse one rule file into { title, rules: [{ id, text, neverOverride, why, source }] }. */
export function parseRules(text, file = 'rules') {
  const lines = text.split('\n');
  const title = (lines.find((l) => l.startsWith('# ')) ?? '').slice(2).trim();
  if (!title) throw new SyncError(`${file}: missing "# Title" line`);
  const rules = [];
  lines.forEach((line, i) => {
    const m = RULE_LINE.exec(line);
    if (!m) return;
    const why = WHY_LINE.exec(lines[i + 1] ?? '');
    rules.push({
      id: m[1],
      text: m[2],
      neverOverride: m[2].trim().endsWith('(never override)'),
      why: why?.[1] ?? null,
      source: why?.[2] ?? null,
    });
  });
  return { title, rules };
}

/** Read the rule files of the given layers, in layer order then file name order. */
export function loadRules(sourceDir, layers) {
  const files = [];
  for (const layer of layers) {
    const dir = path.join(sourceDir, layer, 'rules');
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir).filter((n) => n.endsWith('.md')).sort()) {
      const rel = path.posix.join(layer, 'rules', name);
      files.push({ path: rel, ...parseRules(fs.readFileSync(path.join(dir, name), 'utf8'), rel) });
    }
  }
  return files;
}

/** Render RULES.md: headings demoted, why/source comments stripped, overridden rules replaced by a pointer. */
export function renderRules(ruleFiles, { version, overrides = [] }) {
  const overridden = new Set(overrides.map((o) => o.id));
  const out = [
    `# Shared rules (AI-Master-Instructions ${version})`,
    '',
    'Generated by `.claude/master/sync.mjs`; don\'t edit. A project overrides a rule by id in AGENTS.md "Overrides" and `.ai-master.json`.',
  ];
  for (const file of ruleFiles) {
    out.push('', `## ${file.title}`, '');
    for (const rule of file.rules) {
      out.push(
        overridden.has(rule.id)
          ? `- **${rule.id}** Overridden by this project: see AGENTS.md "Overrides".`
          : `- **${rule.id}** ${rule.text}`,
      );
    }
  }
  return out.join('\n') + '\n';
}

// ---------- catalog, manifest, selection ----------

export function loadCatalog(sourceDir) {
  const file = path.join(sourceDir, 'catalog.json');
  if (!fs.existsSync(file)) throw new SyncError(`no catalog.json in ${sourceDir}`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

export function readManifest(targetDir) {
  const file = path.join(targetDir, MANIFEST);
  if (!fs.existsSync(file)) throw new SyncError(`no ${MANIFEST} in ${targetDir}; see the bootstrap-project skill`);
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  manifest.layers ??= ['core'];
  manifest.exclude ??= [];
  manifest.overrides ??= [];
  if (!manifest.version) throw new SyncError(`${MANIFEST}: "version" is required (a master tag such as v0.1.0)`);
  return manifest;
}

/** Hash of the manifest's meaning, so whitespace edits don't count as drift. */
export function manifestHash(manifest) {
  const { version, layers, exclude, overrides } = manifest;
  return sha256(JSON.stringify({ version, layers, exclude, overrides }));
}

/** Validate the manifest against the catalog and rules; return the items to sync. */
export function select(catalog, ruleFiles, manifest) {
  const known = new Set(catalog.layers);
  for (const layer of manifest.layers) {
    if (!known.has(layer)) throw new SyncError(`unknown layer "${layer}"; known: ${catalog.layers.join(', ')}`);
  }
  if (!manifest.layers.includes('core')) throw new SyncError('layer "core" is required');

  const itemIds = new Set(catalog.items.map((i) => i.id));
  for (const ex of manifest.exclude) {
    if (!itemIds.has(ex.id)) throw new SyncError(`exclude: unknown item "${ex.id}"`);
    if (!ex.reason) throw new SyncError(`exclude "${ex.id}": a reason is required`);
  }

  const rules = new Map(ruleFiles.flatMap((f) => f.rules).map((r) => [r.id, r]));
  for (const ov of manifest.overrides) {
    const rule = rules.get(ov.id);
    if (!rule) throw new SyncError(`override: unknown rule "${ov.id}" in the selected layers`);
    if (rule.neverOverride) throw new SyncError(`override: ${ov.id} is marked "never override"`);
    if (!ov.reason) throw new SyncError(`override "${ov.id}": a reason is required`);
  }

  const excluded = new Set(manifest.exclude.map((e) => e.id));
  // Layer order decides precedence: a later layer's item with the same dest wins.
  const byDest = new Map();
  for (const layer of catalog.layers.filter((l) => manifest.layers.includes(l))) {
    for (const item of catalog.items) {
      if (item.layer === layer && SYNCED_KINDS.has(item.kind) && !excluded.has(item.id)) byDest.set(item.dest, item);
    }
  }
  return [...byDest.values()];
}

// ---------- file plan ----------

/** Build { relPath: Buffer } for everything sync writes, plus the executable set. */
export function plan(sourceDir, catalog, manifest, scriptSource) {
  const ruleFiles = loadRules(sourceDir, catalog.layers.filter((l) => manifest.layers.includes(l)));
  const items = select(catalog, ruleFiles, manifest);
  const files = new Map();
  const executable = new Set();
  for (const item of items) {
    const src = path.join(sourceDir, item.path);
    if (!fs.existsSync(src)) throw new SyncError(`catalog item ${item.id}: missing ${item.path}`);
    for (const rel of walk(src)) {
      const dest = rel === '' ? item.dest : path.posix.join(item.dest, rel);
      const abs = rel === '' ? src : path.join(src, rel);
      files.set(dest, fs.readFileSync(abs));
      if (dest.endsWith('.sh') || dest.endsWith('.py')) executable.add(dest);
    }
  }
  files.set(RULES_OUT, Buffer.from(renderRules(ruleFiles, manifest)));
  files.set(SCRIPT_OUT, fs.readFileSync(scriptSource));
  executable.add(SCRIPT_OUT);
  return { files, executable, items };
}

/** Relative file paths under a file or directory ('' for a single file). */
function walk(abs) {
  if (fs.statSync(abs).isFile()) return [''];
  const out = [];
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    const child = path.join(abs, entry.name);
    if (entry.isDirectory()) out.push(...walk(child).map((r) => path.posix.join(entry.name, r)));
    else out.push(entry.name);
  }
  return out.sort();
}

// ---------- budget ----------

export function measure(targetDir, files = BUDGET_FILES) {
  let lines = 0;
  let bytes = 0;
  for (const rel of files) {
    const abs = path.join(targetDir, rel);
    if (!fs.existsSync(abs)) continue;
    const buf = fs.readFileSync(abs);
    bytes += buf.length;
    lines += buf.toString('utf8').split('\n').length - (buf.at(-1) === 0x0a ? 1 : 0);
  }
  return { lines, bytes };
}

export function budgetProblems(size, budget) {
  const problems = [];
  if (size.lines > budget.lines) problems.push(`${size.lines} lines > ${budget.lines}`);
  if (size.bytes > budget.bytes) problems.push(`${size.bytes} bytes > ${budget.bytes}`);
  return problems;
}

// ---------- sync and check ----------

export function sync({ targetDir, sourceDir, dryRun = false, log = console.log }) {
  const manifest = readManifest(targetDir);
  const catalog = loadCatalog(sourceDir);
  const scriptSource = path.join(sourceDir, 'sync', 'sync.mjs');
  const { files, executable } = plan(sourceDir, catalog, manifest, scriptSource);
  const oldLock = readLock(targetDir);

  // Never silently replace a project's own file: it must be removed or the item excluded first.
  const owned = new Set(Object.keys(oldLock?.files ?? {}));
  const clashes = [...files].filter(([rel, buf]) => {
    const abs = path.join(targetDir, rel);
    return !owned.has(rel) && fs.existsSync(abs) && !fs.readFileSync(abs).equals(buf);
  });
  if (clashes.length) {
    throw new SyncError(`would overwrite project files: ${clashes.map(([rel]) => rel).join(', ')}. Delete them (if the master version replaces them) or exclude the item in ${MANIFEST}.`);
  }

  const changes = [];
  for (const [rel, buf] of files) {
    const abs = path.join(targetDir, rel);
    const same = fs.existsSync(abs) && fs.readFileSync(abs).equals(buf);
    if (!same) changes.push(`${fs.existsSync(abs) ? 'update' : 'add'} ${rel}`);
    if (!dryRun && !same) {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, buf);
    }
    if (!dryRun && executable.has(rel)) fs.chmodSync(abs, 0o755);
  }
  for (const rel of Object.keys(oldLock?.files ?? {})) {
    if (files.has(rel) || !fs.existsSync(path.join(targetDir, rel))) continue;
    changes.push(`remove ${rel}`);
    if (!dryRun) removeAndPrune(targetDir, rel);
  }

  const lock = {
    version: manifest.version,
    commit: gitCommit(sourceDir),
    manifest: manifestHash(manifest),
    budget: catalog.budget.consumer,
    files: Object.fromEntries([...files].sort(([a], [b]) => a.localeCompare(b)).map(([rel, buf]) => [rel, sha256(buf)])),
  };
  if (!dryRun) {
    fs.writeFileSync(path.join(targetDir, LOCK), JSON.stringify(lock, null, 2) + '\n');
    updatePrettierIgnore(targetDir, [...files.keys()], log);
  }

  for (const c of changes) log(`${dryRun ? '[dry-run] ' : ''}${c}`);
  log(`${changes.length} change(s); AI-Master-Instructions ${manifest.version} (${lock.commit.slice(0, 12)})`);

  const problems = budgetProblems(measure(targetDir), lock.budget);
  if (problems.length) {
    throw new SyncError(`start-up size over budget (${BUDGET_FILES.join(' + ')}): ${problems.join(', ')}. Shorten AGENTS.md or exclude layers.`);
  }
  return { changes, lock };
}

/** Verify synced files, manifest and size budget against the lock. Needs no access to the master. */
export function check({ targetDir }) {
  const lock = readLock(targetDir);
  if (!lock) throw new SyncError(`no ${LOCK}; run node ${SCRIPT_OUT}`);
  const problems = [];
  const manifest = readManifest(targetDir);
  if (manifestHash(manifest) !== lock.manifest) problems.push(`${MANIFEST} changed since the last sync; run node ${SCRIPT_OUT}`);
  for (const [rel, hash] of Object.entries(lock.files)) {
    const abs = path.join(targetDir, rel);
    if (!fs.existsSync(abs)) problems.push(`missing ${rel}`);
    else if (sha256(fs.readFileSync(abs)) !== hash) problems.push(`modified ${rel} (synced files are edited in the master, rule SRC-06)`);
  }
  const over = budgetProblems(measure(targetDir), lock.budget);
  if (over.length) problems.push(`start-up size over budget: ${over.join(', ')}`);
  return problems;
}

// ---------- helpers ----------

export function sha256(data) {
  return createHash('sha256').update(data).digest('hex');
}

function readLock(targetDir) {
  const file = path.join(targetDir, LOCK);
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
}

function gitCommit(dir) {
  try {
    return execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unknown';
  }
}

function removeAndPrune(targetDir, rel) {
  fs.rmSync(path.join(targetDir, rel), { force: true });
  let dir = path.dirname(path.join(targetDir, rel));
  const root = path.resolve(targetDir);
  while (dir !== root && fs.existsSync(dir) && fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir);
    dir = path.dirname(dir);
  }
}

/** Keep Prettier off synced files, which it would otherwise reformat (rule SRC-06). */
function updatePrettierIgnore(targetDir, synced, log) {
  const ignoreFile = path.join(targetDir, '.prettierignore');
  const pkgFile = path.join(targetDir, 'package.json');
  const usesPrettier =
    fs.existsSync(ignoreFile) ||
    fs.readdirSync(targetDir).some((n) => n.startsWith('.prettierrc') || n.startsWith('prettier.config')) ||
    (fs.existsSync(pkgFile) && /"prettier"/.test(fs.readFileSync(pkgFile, 'utf8')));
  if (!usesPrettier) return;

  const entries = new Set([LOCK, '.claude/master/']);
  for (const rel of synced) {
    const skill = /^(\.claude\/skills\/[^/]+\/)/.exec(rel);
    entries.add(skill ? skill[1] : rel);
  }
  const block = [PRETTIER_START, ...[...entries].sort(), PRETTIER_END].join('\n');
  const old = fs.existsSync(ignoreFile) ? fs.readFileSync(ignoreFile, 'utf8') : '';
  const start = old.indexOf(PRETTIER_START);
  const end = old.indexOf(PRETTIER_END);
  const next =
    start >= 0 && end > start
      ? old.slice(0, start) + block + old.slice(end + PRETTIER_END.length)
      : (old && !old.endsWith('\n') ? old + '\n' : old) + (old ? '\n' : '') + block + '\n';
  if (next !== old) {
    fs.writeFileSync(ignoreFile, next);
    log('update .prettierignore (ai-master block)');
  }
}

function resolveSource(argSource, version) {
  const dir = argSource ?? process.env.AI_MASTER_DIR;
  if (dir) return { dir: path.resolve(dir), cleanup: () => {} };
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-master-'));
  execFileSync('git', ['clone', '--quiet', '--depth', '1', '--branch', version, MASTER_REPO, tmp], { stdio: 'inherit' });
  return { dir: tmp, cleanup: () => fs.rmSync(tmp, { recursive: true, force: true }) };
}

function parseArgs(argv) {
  const args = { check: false, dryRun: false, source: null, target: process.cwd() };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') args.check = true;
    else if (a === '--dry-run') args.dryRun = true;
    else if (a === '--source') args.source = argv[++i];
    else if (a === '--target') args.target = path.resolve(argv[++i]);
    else throw new SyncError(`unknown argument ${a}`);
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.check) {
    const problems = check({ targetDir: args.target });
    for (const p of problems) console.error(`ai-master check: ${p}`);
    if (problems.length) process.exit(1);
    console.log('ai-master check: OK');
    return;
  }
  const { version } = readManifest(args.target);
  const source = resolveSource(args.source, version);
  try {
    sync({ targetDir: args.target, sourceDir: source.dir, dryRun: args.dryRun });
  } finally {
    source.cleanup();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    main();
  } catch (err) {
    console.error(`ai-master: ${err instanceof SyncError ? err.message : err.stack}`);
    process.exit(1);
  }
}

