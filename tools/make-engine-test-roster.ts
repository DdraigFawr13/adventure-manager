// Writes the engine-test roster (D-110, PLAN §11a): 30 seeded adventurers whose hoverable
// numbers are engine Values with their parts, so the ledger shows breakdowns it never computes
// (D-078, GAME-02). Throwaway fixture until the roster system exists; numbers are illustrative.
// Usage: node tools/make-engine-test-roster.ts
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ATTRIBUTES, makeValue, RngStream, type Value } from '@adventure-manager/engine';
import ledgerText from '../packages/content/data/engine-test-ledger.en.json' with { type: 'json' };

const SEED = 'engine-test-roster';
const ROWS = 30;
const CAUSE = 'tool.make-engine-test-roster';

const ancestries = [
  ['ancestry.marchfolk', 5],
  ['ancestry.stonewright', 2],
  ['ancestry.lanthe', 2],
  ['ancestry.barrowborn', 2],
] as const;
const classes = ['class.warrior', 'class.rogue', 'class.cleric'] as const;
const classWageCopper: Record<(typeof classes)[number], number> = {
  'class.warrior': 60,
  'class.rogue': 54,
  'class.cleric': 48,
};
const leanings: Record<(typeof classes)[number], readonly string[]> = {
  'class.warrior': ['might', 'toughness'],
  'class.rogue': ['agility', 'stealth'],
  'class.cleric': ['resolve', 'lore'],
};
const ageRange: Record<(typeof ancestries)[number][0], [number, number]> = {
  'ancestry.marchfolk': [19, 41],
  'ancestry.stonewright': [34, 96],
  'ancestry.lanthe': [48, 210],
  'ancestry.barrowborn': [19, 39],
};
const ancestryLean: Record<(typeof ancestries)[number][0], string> = {
  'ancestry.marchfolk': 'wits',
  'ancestry.stonewright': 'toughness',
  'ancestry.lanthe': 'lore',
  'ancestry.barrowborn': 'stealth',
};

const rng = RngStream.detached(SEED, 'tool.roster');
const used = new Set<string>();
const rows = [];
for (let i = 0; i < ROWS; i += 1) {
  const ancestryId = rng.weighted(ancestries);
  const classId = rng.pick(classes);
  const parts = ledgerText.names[ancestryId];
  let name = '';
  do name = `${rng.pick(parts.given)} ${rng.pick(parts.family)}`;
  while (used.has(name));
  used.add(name);

  const level = rng.between(1, 8);
  const [ageMin, ageMax] = ageRange[ancestryId];
  const condition = rng.weighted([
    ['fit', 20],
    ['hurt', 5],
    ['badlyHurt', 2],
    ['resting', 3],
  ] as const);

  const attributes: Record<string, Value> = {};
  for (const attribute of ATTRIBUTES) {
    const valueParts = [];
    if (leanings[classId].includes(attribute)) valueParts.push({ sourceId: 'training', amount: 1 });
    if (ancestryLean[ancestryId] === attribute)
      valueParts.push({ sourceId: 'ancestry', amount: 2 });
    if (attribute === 'might' && rng.chance(2500))
      valueParts.push({ sourceId: 'gear.blade', amount: 1 });
    if (attribute === 'agility' && classId === 'class.warrior' && rng.chance(4000)) {
      valueParts.push({ sourceId: 'gear.mail', amount: -1 });
    }
    if (condition !== 'fit' && (attribute === 'might' || attribute === 'agility')) {
      valueParts.push({ sourceId: 'wound.hurt', amount: condition === 'badlyHurt' ? -3 : -1 });
    }
    attributes[attribute] = makeValue(rng.between(6, 14), CAUSE, valueParts);
  }

  const wageParts = [{ sourceId: 'level', amount: level * 6 }];
  if (rng.chance(5000)) wageParts.push({ sourceId: 'renown', amount: rng.between(2, 20) });
  if (rng.chance(3000)) wageParts.push({ sourceId: 'clause.haggled', amount: -rng.between(2, 10) });
  const moraleParts = [];
  if (rng.chance(5000)) moraleParts.push({ sourceId: 'morale.win', amount: rng.between(1, 3) });
  if (rng.chance(2000)) moraleParts.push({ sourceId: 'morale.loss', amount: -rng.between(2, 4) });
  if (rng.chance(1000)) moraleParts.push({ sourceId: 'morale.unpaid', amount: -2 });
  if (condition === 'resting') moraleParts.push({ sourceId: 'morale.rest', amount: 1 });

  rows.push({
    id: `adv.test-${String(i + 1).padStart(2, '0')}`,
    name,
    ancestryId,
    classId,
    level,
    age: rng.between(ageMin, ageMax),
    condition,
    morale: makeValue(rng.between(9, 14), CAUSE, moraleParts),
    attributes,
    wageCopper: makeValue(classWageCopper[classId], CAUSE, wageParts),
    contractWeeks: rng.between(2, 60),
  });
}

const out = fileURLToPath(
  new URL('../packages/content/data/engine-test-roster.json', import.meta.url),
);
const note = `Generated by tools/make-engine-test-roster.ts (seed ${SEED}); do not edit by hand.`;
writeFileSync(out, `${JSON.stringify({ _note: note, rows }, null, 2)}\n`);
console.log(`Wrote ${rows.length} adventurers to ${out}`);
